#!/usr/bin/env bash
# Embeds Fixtures/*.json and Fixtures/*.txt into Packages/DroverKit/Sources/DroverKit/Mock/Fixtures+Generated.swift.
# Each file becomes a raw multi-line string; Swift drops the final newline of such a string, so the
# FixturesInSync test compares after removing ONE trailing newline from both sides.
set -euo pipefail
cd "$(dirname "$0")/.."
out="Packages/DroverKit/Sources/DroverKit/Mock/Fixtures+Generated.swift"
mkdir -p "$(dirname "$out")"
tmp="$(mktemp)"
trap 'rm -f "$tmp"' EXIT
{
  echo '// Generated by script/gen-fixtures.sh from Fixtures/. Do not edit.'
  echo 'import Foundation'
  echo
  echo 'public enum Fixtures {'
  echo '    public static let all: [String: String] = ['
  for f in $(ls Fixtures | LC_ALL=C sort); do
    case "$f" in *.json|*.txt) ;; *) continue ;; esac
    if grep -qF '"""#' "Fixtures/$f"; then
      echo "gen-fixtures: Fixtures/$f contains \"\"\"# and cannot be embedded" >&2
      exit 1
    fi
    if grep -qF '\#' "Fixtures/$f"; then
      echo "gen-fixtures: Fixtures/$f contains a backslash-hash sequence and cannot be embedded" >&2
      exit 1
    fi
    printf '        "%s": #"""\n' "$f"
    cat "Fixtures/$f"
    # make sure the closing delimiter sits on its own line
    if [ -n "$(tail -c1 "Fixtures/$f")" ]; then echo; fi
    echo '"""#,'
  done
  echo '    ]'
  echo
  echo '    public static func data(_ name: String) -> Data? { all[name].map { Data($0.utf8) } }'
  echo '}'
} > "$tmp"
mv "$tmp" "$out"
trap - EXIT
echo "wrote $out"
